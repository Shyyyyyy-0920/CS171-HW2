#pragma once

#include "Surface.hpp"

namespace cs171 {

/// \brief Bezier patches uploaded to the GPU, drawn as `GL_PATCHES` and tessellated by the tessellation shaders.
///
/// Every patch sends its `(degreeU + 1) * (degreeV + 1)` control points, ordered as `Surface::points`, to the
/// tessellation evaluation shader, which evaluates the surface at the points generated by the tessellator.
/// No tessellation control shader is used: the tessellation levels are set here with `glPatchParameterfv`,
/// so that patches of any degrees can be drawn.
///
/// The OpenGL objects are owned by this class and released in the destructor,
/// so keep a compatible OpenGL context current meanwhile.
///
/// \see https://www.khronos.org/opengl/wiki/Tessellation
class PatchMesh {
public:
  /// \brief Uploads the control points of `patches`, which must be Bezier patches of the same degrees.
  explicit PatchMesh(std::vector<Surface> const &patches);
  ~PatchMesh() noexcept;

  // Each instance owns its OpenGL objects, so copying is disabled.
  PatchMesh(PatchMesh const &) = delete;
  PatchMesh &operator=(PatchMesh const &) = delete;

  /// \brief Returns the degree of the patches along u.
  [[nodiscard]] usize DegreeU() const { return degreeU_; }

  /// \brief Returns the degree of the patches along v.
  [[nodiscard]] usize DegreeV() const { return degreeV_; }

  /// \brief Draws all patches, each tessellated into `level x level` cells.
  void Draw(float level) const;

private:
  // OpenGL vertex array and vertex buffer objects.
  unsigned int vao_{}, vbo_{};
  // Degrees shared by all patches.
  usize degreeU_{}, degreeV_{};
  // Total number of control points.
  int count_{};
};

} // namespace cs171
